/**
 * Shared SEO building blocks: Open Graph images and JSON-LD fragments that
 * several page types need. Keeps the publisher entity, breadcrumbs and FAQ
 * markup identical everywhere.
 */
import type { Metadata } from "next";
import type { Faq } from "@/content/types";
import { site } from "@/content/site";

/** Google shows roughly 60 characters of a title before truncating it. */
const TITLE_LIMIT = 60;
const TITLE_SUFFIX = ` | ${site.name}`;

/**
 * Page title for metadata. Keeps the layout's " | CleaningProductsReviews.com" suffix only when
 * the whole title still fits; otherwise the page's own words win and the brand is dropped
 * (search results already show the site name above the title).
 */
export function seoTitle(base: string): NonNullable<Metadata["title"]> {
  return base.length + TITLE_SUFFIX.length <= TITLE_LIMIT ? base : { absolute: base };
}

/** Meta description capped at 160 characters, cut on a word boundary. */
export function seoDescription(text: string, max = 160): string {
  const clean = text.replace(/\s+/g, " ").trim();
  if (clean.length <= max) return clean;
  const cut = clean.slice(0, max - 1);
  const atWord = cut.slice(0, cut.lastIndexOf(" ")).replace(/[\s,;:—–-]+$/, "");
  return `${atWord}…`;
}

/** Site-wide share image (1200x630), generated by `npm run images`. */
export const DEFAULT_OG_IMAGE = { url: `${site.domain}/og-default.jpg`, width: 1200, height: 630, alt: site.name };

/** Raster copy of a product illustration, for og:image and structured data (SVG is not supported there). */
export function productImageUrl(image: string) {
  return site.domain + image.replace(/\.svg$/, ".jpg");
}

export function productOgImage(image: string, alt: string) {
  return { url: productImageUrl(image), width: 1200, height: 900, alt };
}

export const ORGANIZATION = {
  "@type": "Organization",
  "@id": `${site.domain}/#organization`,
  name: site.name,
  url: site.domain,
  logo: { "@type": "ImageObject", url: `${site.domain}/logo.png`, width: 512, height: 512 },
};

/** Reference to the publisher entity, for author/publisher fields. */
export const ORGANIZATION_REF = { "@id": ORGANIZATION["@id"] };

export function breadcrumbSchema(trail: { name: string; url: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: trail.map((t, i) => ({ "@type": "ListItem", position: i + 1, name: t.name, item: t.url })),
  };
}

export function faqSchema(faqs: Faq[]) {
  if (!faqs.length) return null;
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map((f) => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })),
  };
}
